param(
  [string]$Distro = "",     # defaults to the distro named in this script's own UNC path
  [switch]$Remove
)
# Wires the note to start at Windows login.
#
# Two things this gets right, both learned the hard way:
#
# 1. The shortcut does NOT target the .cmd on the WSL filesystem. A logon shortcut to a UNC
#    path depends on the distro already being reachable; if WSL has not started yet the
#    shortcut fails silently and the user gets no note and no error. So the shortcut targets a
#    small LOCAL launcher generated here, which starts WSL first and only then runs the note.
# 2. It derives its own location ($PSScriptRoot) instead of hardcoding a home directory, so
#    the same file works from a repo checkout and from an installed copy, for any user.
$ErrorActionPreference = "Stop"
$startup = [Environment]::GetFolderPath('Startup')
$lnkPath = Join-Path $startup "Board note.lnk"

if ($Remove) {
  if (Test-Path $lnkPath) { Remove-Item $lnkPath -Force; Write-Output "removed: $lnkPath" }
  else { Write-Output "no shortcut to remove" }
  $localCmd = Join-Path (Join-Path $env:LOCALAPPDATA "hermes-board-note") "start.cmd"
  if (Test-Path $localCmd) { Remove-Item $localCmd -Force; Write-Output "removed: $localCmd" }
  exit 0
}

$here = $PSScriptRoot
if (-not $here) { Write-Output "ERROR: cannot determine this script's directory"; exit 1 }
if ($here -notlike "\\wsl.localhost\*") {
  Write-Output "ERROR: run this from the WSL filesystem (\\wsl.localhost\...), so the note's home is known."
  exit 1
}
# \\wsl.localhost\<distro>\rest\of\path
if (-not $Distro) { $Distro = ($here -split '\\')[3] }
$scriptPath = Join-Path $here "board-note.ps1"
if (-not (Test-Path $scriptPath)) { Write-Output "ERROR: board-note.ps1 not found next to this script"; exit 1 }

$stage = Join-Path $env:LOCALAPPDATA "hermes-board-note"
New-Item -ItemType Directory -Force -Path $stage | Out-Null
$localCmd = Join-Path $stage "start.cmd"

# ASCII-only: the console codepage mangles anything else in a .cmd.
$body = @"
@echo off
rem Generated by install-startup.ps1 -- waits for WSL, then starts the board note.
setlocal
set "DISTRO=$Distro"
set "SCRIPT=$scriptPath"
for /l %%i in (1,1,20) do (
  wsl.exe -d %DISTRO% -e true >nul 2>&1 && goto ready
  timeout /t 2 >nul
)
echo Board note: WSL distro "%DISTRO%" did not become ready; not starting.
exit /b 1
:ready
start "" powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -Command "& '%SCRIPT%'"
endlocal
"@
Set-Content -Path $localCmd -Value $body -Encoding ASCII

$ws = New-Object -ComObject WScript.Shell
$lnk = $ws.CreateShortcut($lnkPath)
$lnk.TargetPath = $localCmd
$lnk.WorkingDirectory = $stage
$lnk.Description = "Hermes Kanban board sticky note"
$lnk.Save()

if (Test-Path $lnkPath) {
  Write-Output "startup: $lnkPath"
  Write-Output "   targets $localCmd (waits for WSL '$Distro', then runs $scriptPath)"
  Write-Output "   remove with: install-startup.ps1 -Remove"
} else {
  Write-Output "FAILED to create the shortcut"
  exit 1
}
